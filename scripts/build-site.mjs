// Copy the static public site (/site) into dist/ root, alongside the SPA which
// vite builds into dist/studio. Run after `vite build`. See docs/public-site.md.
import {
  copyFileSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  writeFileSync,
} from "node:fs";
import { createHash } from "node:crypto";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const site = join(root, "site");
const dist = join(root, "dist");
mkdirSync(dist, { recursive: true });

const FILES = [
  "index.html",
  "privacy.html",
  "terms.html",
  "site.css",
  "robots.txt",
  "sitemap.xml",
  "llms.txt",
  // Brand / SEO assets (generated by scripts/make-assets.mjs).
  "favicon.svg",
  "favicon.ico",
  "apple-touch-icon.png",
  "og.png",
];

// site.css is served with a long cache but isn't content-hashed, so stamp its
// <link> with a content hash. The HTML pages themselves revalidate (no long
// cache), so returning visitors always pick up a changed stylesheet.
const cssHash = createHash("sha256")
  .update(readFileSync(join(site, "site.css")))
  .digest("hex")
  .slice(0, 8);

for (const f of FILES) {
  if (f.endsWith(".html")) {
    const html = readFileSync(join(site, f), "utf8").replaceAll(
      '"/site.css"',
      `"/site.css?v=${cssHash}"`,
    );
    writeFileSync(join(dist, f), html);
  } else {
    copyFileSync(join(site, f), join(dist, f));
  }
}

// Locally-served fonts for the public pages (no remote fonts, spec §15).
const fontsSrc = join(site, "fonts");
const fontsDst = join(dist, "fonts");
mkdirSync(fontsDst, { recursive: true });
let fontCount = 0;
for (const f of readdirSync(fontsSrc)) {
  copyFileSync(join(fontsSrc, f), join(fontsDst, f));
  fontCount++;
}

console.log(
  `Copied ${FILES.length} public-site files + ${fontCount} fonts into dist/`,
);
